package com.glyph.glyph_v3.ui.auth.data

import com.glyph.glyph_v3.ui.auth.models.Country

/**
 * Static country list for the phone number country picker.
 *
 * Data is derived from the existing [com.glyph.glyph_v3.utils.PhoneNumberUtil]
 * country calling codes map, extended with all countries commonly used in
 * messaging apps. Flag emoji are computed at class-load time from ISO2 codes.
 *
 * Countries are ordered by calling code for natural grouping.
 */
object CountryData {

    val ALL_COUNTRIES: List<Country> by lazy {
        rawEntries.map { (iso2, name, callingCode) ->
            Country(
                iso2 = iso2,
                name = name,
                callingCode = callingCode,
                flagEmoji = Country.flagEmojiFromIso2(iso2)
            )
        }.sortedWith(compareBy<Country> { it.callingCode.toIntOrNull() ?: 0 }.thenBy { it.name })
    }

    /**
     * Returns the default country for the user's locale/SIM, or India (+91) as fallback.
     */
    fun detectDefault(iso2Hint: String?): Country {
        val hint = iso2Hint?.trim()?.uppercase()?.takeIf { it.length == 2 }
        if (hint != null) {
            val match = ALL_COUNTRIES.firstOrNull { it.iso2 == hint }
            if (match != null) return match
        }
        // Fallback to India
        return ALL_COUNTRIES.firstOrNull { it.iso2 == "IN" }
            ?: ALL_COUNTRIES.first()
    }

